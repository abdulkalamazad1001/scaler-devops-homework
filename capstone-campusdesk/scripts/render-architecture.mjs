import { createRequire } from 'node:module';
import { pathToFileURL, fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';
const require = createRequire(new URL('../../tools/browser/package.json', import.meta.url));
const { Graphviz } = await import(pathToFileURL(require.resolve('@hpcc-js/wasm-graphviz')).href);
const { chromium } = require('playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dot = `digraph CampusDesk {
  graph [rankdir=LR, bgcolor="white", pad=0.3, nodesep=0.5, ranksep=0.7];
  node [shape=box, style="rounded,filled", fillcolor="#f2f6f4", color="#b3c6be", fontname="Arial", fontsize=17, margin="0.22,0.15"];
  edge [color="#788e84", arrowsize=0.7];
  browser [label="Browser"];
  ingress [label="Traefik\nIngress"];
  frontend [label="React + Nginx\n2 replicas"];
  backend [label="FastAPI\n2-4 replicas", fillcolor="#dbefe5"];
  database [label="PostgreSQL\npersistent volume", shape=cylinder];
  prometheus [label="Prometheus"];
  grafana [label="Grafana"];
  github [label="GitHub source"];
  ci [label="Tests + build\nTrivy scan"];
  registry [label="GHCR\ncommit SHA"];
  argo [label="Argo CD\nHelm templates"];
  browser -> ingress; ingress -> frontend; ingress -> backend;
  frontend -> backend; backend -> database;
  backend -> prometheus [label=" /metrics",fontname="Arial",fontsize=12]; prometheus -> grafana;
  github -> ci; ci -> registry; github -> argo; argo -> backend [style=dashed]; registry -> backend [style=dashed];
}`;
const graphviz = await Graphviz.load();
const svg = graphviz.layout(dot, 'svg', 'dot');
await fs.writeFile(path.join(root, 'evidence/architecture.svg'), svg);
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1800,height:1100}});
await page.setContent(`<html><body style="margin:0;background:white">${svg}</body></html>`);
await page.locator('svg').screenshot({path:path.join(root,'evidence/architecture.png')});
await browser.close();
